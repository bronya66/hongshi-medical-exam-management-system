import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from db import query_all  # noqa: E402


def build_common_content(title: str, material_id: int) -> str:
    return f"""{title}
资料编号：{material_id}

一、核心知识框架
1. 本资料围绕考试高频内容整理，建议先建立章节地图，再逐条攻克细分考点。
2. 每个知识点至少完成“概念定义-典型题型-易错陷阱-答题模板”四步学习闭环。
3. 复习时遵循“先理解、再记忆、后输出”的顺序，避免只背不练。

二、重点考点拆解
1. 高频考点A：明确命题方式、关键词和常见干扰项，形成快速识别能力。
2. 高频考点B：对照历年真题总结出题角度，准备两种以上答题路径。
3. 高频考点C：结合临床或案例场景进行迁移练习，提升应用能力。
4. 高频考点D：整理近三年变化内容，更新旧笔记，避免使用过时表述。

三、典型题型与答题模板
1. 选择题：先审题干限定词，再排除绝对化选项，最后回扣教材原句。
2. 案例题：按“主诉-关键体征-鉴别诊断-处理原则”结构作答。
3. 论述题：采用“总-分-总”框架，分点陈述，保证逻辑清晰与术语规范。
4. 主观题：优先给出观点句，再补充论据句和总结句。

四、易错点与纠偏建议
1. 易错点：概念相近但边界不同，答题时容易混淆。
   纠偏：建立对照表，按“定义-特征-适用场景”三列进行记忆。
2. 易错点：只记结论不记依据，导致变式题失分。
   纠偏：每个结论补充至少1条机制或依据。
3. 易错点：练习量不足，时间分配不合理。
   纠偏：采用45分钟专注+10分钟复盘的番茄节奏。

五、阶段学习计划（建议执行7天）
第1天：通读资料并标注陌生术语，完成第一轮理解。
第2天：完成核心知识点背诵，输出思维导图。
第3天：完成配套题训练并记录错因。
第4天：专项攻克薄弱章节，二次整理错题。
第5天：限时模拟训练，校准答题节奏。
第6天：回顾高频易错点，完善答题模板。
第7天：整合复盘，形成个人冲刺清单。

六、复盘清单（每次学习后自检）
1. 今天是否完成计划内任务，并记录真实完成率。
2. 今天新增了哪些可迁移的解题策略。
3. 哪些错误是知识盲区，哪些是审题或粗心问题。
4. 明天的优先任务是什么，预计投入多少分钟。

附：建议把本资料与课堂讲义、错题本、历年真题联动使用。若时间紧张，优先攻克“高频+高错”交叉区域。
"""


def build_general_content(material_id: int) -> str:
    return f"""综合复习资料（通用强化版）
资料编号：{material_id}

一、复习总策略
1. 先做诊断：用一套小测定位薄弱章节，按错误密度排序。
2. 再做分层：把知识点分为“已掌握、半掌握、未掌握”三层管理。
3. 最后冲刺：把时间集中在“高频且未掌握”内容上。
4. 每周至少完成一次综合回顾，避免知识点碎片化。

二、通用答题方法
1. 选择题：关键词定位 + 选项对照 + 反证排错。
2. 主观题：结论先行 + 分点展开 + 术语规范。
3. 案例题：问题识别 + 证据提取 + 处理路径。
4. 论述题：总分总结构，观点明确，论据充分。

三、每日执行模板
上午：知识点输入（阅读+标注）
下午：题目训练（限时+计分）
晚上：错题复盘（错因归类+二次作答）
睡前：10分钟回顾当日关键词与模板句。

四、错题复盘标准
1. 错因必须具体到“概念混淆/审题遗漏/计算错误/表达不规范”。
2. 每道错题必须写出“正确思路一句话版”。
3. 三天内再次出现同类错误时，必须回到原章节补课。
4. 错题本每周做一次“再分类”，把高频错点前置。

五、冲刺建议
1. 近7天重点做真题与高频模拟，不再盲目扩展新资料。
2. 每日保留30分钟回顾旧错题，强化长期记忆。
3. 考前一天仅做轻量复盘，保持节奏稳定。
4. 练习时严格计时，提前适应考试节奏。

六、学科联动训练建议
1. 医学专业课：每次复盘至少整理3个“概念-机制-临床意义”链条。
2. 英语：每天固定完成长难句拆解与段落翻译，积累高频表达。
3. 政治：按“原理-材料-结论”三段式训练主观题表达，避免空泛。
4. 综合管理：通过周计划把各科目标量化到每天，避免临近考试突击。

七、冲刺阶段时间分配参考
1. 距考试30天：以系统梳理为主，查漏补缺为辅。
2. 距考试14天：以真题演练为主，强化错题迁移。
3. 距考试7天：以高频清单复盘为主，保持题感与节奏。

八、考前一天执行清单
1. 只做已掌握内容回顾，不再硬啃新知识。
2. 复查易错清单与答题模板，确保作答结构稳定。
3. 提前准备考试用品，保证作息与精神状态。

九、最终提醒
复习效率的关键不在资料数量，而在闭环执行。每次学习都要留下可复用的输出：
- 一页思维导图
- 一组错题改写
- 一套个人答题模板
坚持执行，成绩会稳定提升。
"""


def main() -> None:
    rows = query_all("SELECT id, title, file_path FROM materials WHERE file_path LIKE 'materials/%%.txt' ORDER BY id")
    if not rows:
        print("未查询到 txt 资料")
        return

    min_len = 10**9
    for row in rows:
        material_id = int(row["id"])
        title = str(row.get("title") or "学习资料")
        rel = str(row["file_path"]).replace("/", os.sep)
        abs_path = os.path.join(BASE_DIR, "uploads", rel)
        os.makedirs(os.path.dirname(abs_path), exist_ok=True)

        if material_id == 112:
            content = build_general_content(material_id)
        else:
            content = build_common_content(title, material_id)

        with open(abs_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)

        min_len = min(min_len, len(content))
        print(f"{material_id}\t{len(content)}\t{row['file_path']}")

    print(f"MIN_LEN={min_len}")


if __name__ == "__main__":
    main()
